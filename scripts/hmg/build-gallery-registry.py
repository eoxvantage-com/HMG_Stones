"""Produce shared public metadata from downloaded, visually reviewed HMG originals."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
manifest_path = ROOT / 'docs/hmg/gallery-assets.json'
manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
storage = {a['id']: a for a in json.loads((ROOT / 'docs/hmg/gallery-storage.json').read_text(encoding='utf-8'))['assets']}
for asset in manifest['assets']:
    asset['eligibilityReason'] = ('Showroom or installation photograph with perspective, fixtures and lighting; not an isolated material texture.'
        if asset['category'].startswith('Experience') else 'Factory, stockyard or interior photograph; not an isolated front-facing material texture.')
    stored = storage[asset['id']]
    filename = Path(asset['localUrl']).name
    if stored['sha256'] != asset['sha256'] or stored['bytes'] != asset['bytes'] or stored['path'] != f'gallery/{filename}':
        raise ValueError('Gallery storage verification mismatch')
    asset.pop('url', None)
manifest_path.write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf-8')
assets = [{k:v for k,v in a.items() if k not in ('sha256','bytes')} for a in manifest['assets']]
destination = ROOT / 'src/features/hmg/design/galleryAssets.mjs'
destination.write_text('// Generated by scripts/hmg/build-gallery-registry.py from verified gallery provenance.\nexport const galleryAssets = ' + json.dumps(assets, indent=2) + ';\n', encoding='utf-8')
print('Generated shared metadata for',len(assets),'verified inspiration images')
